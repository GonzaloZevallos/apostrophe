import { existsSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

/** The command that rewrites the committed types file; the staleness failure names it. */
export const TYPES_COMMAND = 'npm run i18n:types'

const WEB_ROOT = join(import.meta.dirname, '..', '..')
export const ENGLISH_DIR = join(WEB_ROOT, 'src', 'copy', 'locales', 'en')
export const TYPES_PATH = join(WEB_ROOT, 'src', 'i18n', 'resources.generated.d.ts')

/** The namespaces of the English files: their names without `.json`, sorted. */
export function englishNamespaces(dir: string = ENGLISH_DIR): readonly string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort()
}

/** The text of the types file for these namespaces: one sorted line per English file. */
export function renderResourceTypes(namespaces: readonly string[]): string {
  const lines = [...namespaces]
    .sort()
    .map((ns) => `  ${JSON.stringify(ns)}: typeof import('../copy/locales/en/${ns}.json')`)
  const resources = lines.length === 0 ? '{}' : `{\n${lines.join('\n')}\n}`
  return [
    `// Generated by \`${TYPES_COMMAND}\` from src/copy/locales/en/*.json. Do not edit by hand.`,
    `import type { KeysOf } from './keys'`,
    ``,
    `export type Resources = ${resources}`,
    ``,
    `/** Every key \`t\` accepts, as \`ns:key\`. */`,
    `export type CopyKey = KeysOf<Resources>`,
    ``,
    `declare module 'i18next' {`,
    `  interface CustomTypeOptions {`,
    `    resources: Resources`,
    `  }`,
    `}`,
    ``,
  ].join('\n')
}

/** What is wrong with the committed text, or null when it matches the folder. */
export function stalenessProblem(committed: string, namespaces: readonly string[]): string | null {
  return committed === renderResourceTypes(namespaces)
    ? null
    : `src/i18n/resources.generated.d.ts disagrees with src/copy/locales/en/*.json: run \`${TYPES_COMMAND}\` and commit the result`
}

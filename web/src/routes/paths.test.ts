import { expect, test } from 'vitest'
import { paths } from './paths'

test('every screen has one path, ids and tokens interpolated', () => {
  expect(paths.home()).toBe('/')
  expect(paths.login()).toBe('/login')
  expect(paths.sales()).toBe('/sales')
  expect(paths.newSale()).toBe('/sales/new')
  expect(paths.sale(7)).toBe('/sales/7')
  expect(paths.customers()).toBe('/customers')
  expect(paths.newCustomer()).toBe('/customers/new')
  expect(paths.customer('3')).toBe('/customers/3')
  expect(paths.editCustomer('3')).toBe('/customers/3/edit')
  expect(paths.customersOwing()).toBe('/customers/owing')
  expect(paths.varieties()).toBe('/varieties')
  expect(paths.variety(5)).toBe('/varieties/5')
  expect(paths.catalog()).toBe('/varieties/catalog')
  expect(paths.entries()).toBe('/varieties/entries')
  expect(paths.newEntry()).toBe('/varieties/entries/new')
  expect(paths.entry(9)).toBe('/varieties/entries/9')
  expect(paths.expenses()).toBe('/expenses')
  expect(paths.newExpense()).toBe('/expenses/new')
  expect(paths.expenseCategories()).toBe('/settings/expense-categories')
  expect(paths.analysis()).toBe('/analysis')
  expect(paths.more()).toBe('/more')
  expect(paths.settings()).toBe('/settings')
  expect(paths.settingsBusiness()).toBe('/settings/business')
  expect(paths.settingsUsers()).toBe('/settings/users')
  expect(paths.settingsAccount()).toBe('/settings/account')
  expect(paths.settingsIntegrations()).toBe('/settings/integrations')
  expect(paths.settingsCatalogMessage()).toBe('/settings/catalog-message')
  expect(paths.invitation('tok')).toBe('/invitation/tok')
  expect(paths.reset('tok')).toBe('/reset/tok')
})

def _rewrite_member(line: str) -> str:
    out = line.replace("[", "~").replace("]", "~").replace("|", "#124;")
    out = out.replace("<", "#60;").replace("{", "#123;").replace("}", "#125;")
    return re.sub(r"(?<!-)>", "#62;", out)


def _is_method(line: str) -> bool:
    cut = line.find(" : ")
    head = line if cut < 0 else line[:cut]
    return "(" in head


def _group_name(line: str) -> str:
    match = _CLASS_NAME.match(line.strip())
    return match.group(1) if match is not None else line.strip()


def _canonical_group(group: list[str], kind: Kind) -> list[str]:
    if kind == "er" or len(group) < 2:
        return group
    opener, closer = group[0], group[-1]
    members = group[1:-1]
    if kind == "class":
        members = [_rewrite_member(m) for m in members]
        attributes = sorted(m for m in members if not _is_method(m))
        methods = sorted(m for m in members if _is_method(m))
        members = attributes + methods
    return [opener, *members, closer]


@dataclass
class _Group:
    opener: str
    nodes: list[str]
    groups: list[_Group]
    closed: bool = False


def _group_id(opener: str) -> str:
    match = _SUBGRAPH_ID.match(opener)
    return match.group(1) if match is not None else opener


def _render_group(group: _Group, depth: int) -> list[str]:
    pad = "  " * depth
    inner = "  " * (depth + 1) if group.opener else pad
    out = [f"{pad}{group.opener}"] if group.opener else []
    child_depth = depth + 1 if group.opener else depth
    children = sorted(
        (_render_group(child, child_depth) for child in group.groups),
        key=lambda lines: (_group_id(lines[0].strip()), lines),
    )
    for lines in children:
        out.extend(lines)
    directions = sorted(n for n in group.nodes if n.startswith("direction "))
    others = sorted(n for n in group.nodes if not n.startswith("direction "))
    out.extend(f"{inner}{node}" for node in [*directions, *others])
    if group.opener and group.closed:
        out.append(f"{pad}end")
    return out


def _canonical_flow(lines: Sequence[str]) -> list[str]:
    root = _Group("", [], [])
    stack = [root]
    edges: list[str] = []
    styles: list[str] = []
    link_styles: list[str] = []
    for raw in lines[1:]:
        line = raw.strip()
        if line.startswith("subgraph "):
            group = _Group(line, [], [])
            stack[-1].groups.append(group)
            stack.append(group)
        elif line == "end" and len(stack) > 1:
            stack.pop().closed = True
        elif line.startswith("linkStyle"):
            link_styles.append(line)
        elif line.startswith(_FLOW_STYLE_WORDS):
            styles.append(line)
        elif _is_flow_edge(line):
            edges.append(line)
        else:
            stack[-1].nodes.append(line)
    return [lines[0], *_render_group(root, 0), *sorted(edges), *sorted(styles), *link_styles]


def _canonical_body(body: Sequence[str], kind: Kind) -> list[str]:
    lines = [line for line in body if line.strip()]
    if not lines:
        return []
    if kind == "flow":
        return _canonical_flow(lines)
    first, rest = lines[0], lines[1:]
    nodes: list[list[str]] = []
    edges: list[str] = []
    group: list[str] | None = None
    for line in rest:
        if group is not None:
            group.append(line)
            if _is_group_close(line):
                nodes.append(_canonical_group(group, kind))
                group = None
        elif _is_relation(line):
            edges.append(line)
        elif _is_group_open(line):
            group = [line]
        else:
            nodes.append([line])
    if group is not None:
        nodes.append(_canonical_group(group, kind))
    nodes.sort(key=lambda node: (_group_name(node[0]), node))
    out = [first]
    for node in nodes:
        out.extend(node)
    out.extend(sorted(edges))
    return out


def finalize(kind: Kind, raw: str) -> str:
    """The canonical form of one generated Markdown file; see the module docstring."""
    lines = [line.rstrip() for line in raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    lines = [line for line in lines if line != HEADER]
    if kind != "index":
        rebuilt: list[str] = []
        cursor = 0
        for start, end in _fences(lines):
            rebuilt.extend(lines[cursor:start])
            rebuilt.extend(_canonical_body(lines[start:end], kind))
            cursor = end
        rebuilt.extend(lines[cursor:])
        lines = rebuilt
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    body = "\n".join(lines)
    return f"{HEADER}\n\n{body}\n" if body else f"{HEADER}\n"

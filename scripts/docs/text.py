"""Canonical form and size rules for generated Markdown that holds Mermaid diagrams.

`finalize(kind, raw)` takes the Markdown of one generated file and returns its canonical
bytes-to-be. The same input in any line order gives the same output:

- Every kind: line endings become `\\n`, trailing whitespace is stripped, the text ends in
  exactly one newline, and `HEADER` is the first line exactly once (any copy already in
  the text is dropped first, so a second run changes nothing).
- Only the inside of a fence that opens with ```` ```mermaid ```` is rewritten; the
  Markdown around it only gets the shared steps. Blank lines inside a diagram are dropped.
- `class`: member type text becomes what Mermaid accepts (`[`/`]` become `~`, `|` becomes
  `#124;`, `<` and `>` become `#60;` and `#62;`, `{` and `}` become `#123;` and `#125;`;
  the `>` of a `->` arrow is left alone). Class groups are sorted by name, each kept whole;
  relation lines are sorted after the groups. Inside a group the attributes come first,
  sorted, then the methods, sorted. A member is a method only when a `(` appears before its
  first ` : `, so an attribute typed `Callable[..., T]` stays an attribute.
- `packages`: node lines (and node groups) are sorted by name, then the edge lines.
- `er`: entity blocks are sorted by name and then the relation lines. The attribute lines
  inside an entity keep the order they came in: it is the column order of the table.
- `flow`: a Mermaid flowchart. Every `subgraph` keeps its `end`, at any depth, and the body is
  re-indented two spaces per depth. At each level nested groups come first, sorted by id,
  then the node lines, sorted. After all the groups come every edge (hoisted out of any
  group), sorted, then the `classDef`/`style`/`class` lines, sorted. A `linkStyle` line
  refers to edges by position, so it is never reordered (it follows the styles in input
  order) and `block_problems` reports it as `flow-linkstyle`. A group with no `end` stays
  without one, so the parse of the staged file fails instead of the text being repaired.
- `index`: the shared steps only.

The module imports nothing from `app` or `tests`.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Literal

HEADER = (
    "<!-- Generated by scripts/docs/generate.py. Do not edit; "
    "run `uv run --no-project python -m scripts.docs.generate` instead. -->"
)

Kind = Literal["class", "packages", "er", "flow", "index"]

MAX_BLOCK_CHARS = 50_000
MAX_BLOCK_EDGES = 500

_FENCE_OPEN = "```mermaid"
_FENCE_CLOSE = "```"
# A relation token: `--`, `..` or `...` plus the arrow heads class and ER diagrams put
# around it (`<|--`, `*--`, `--|>`, `..>`, `||--o{`), delimited by spaces.
_RELATION = re.compile(r"(?<!\S)[<>|*o{}()]*(?:--|\.\.)[<>|*o{}()]*(?!\S)")
_CLASS_NAME = re.compile(r'^(?:class\s+)?("[^"]*"|[^\s{]+)')
_CLASS_DEF = re.compile(r'^class\s+("[^"]*"|[^\s{]+)')
# A flowchart edge: `-->`, `---`, `-.->`, `==>`; the labelled forms (`-->|x|`, `--|x|-->`)
# contain one of them. Quoted node labels are blanked first.
_FLOW_EDGE = re.compile(r"-->|---|-\.->|==>")
_QUOTED = re.compile(r'"[^"]*"')
_SUBGRAPH_ID = re.compile(r"^subgraph\s+([^\s\[]+)")
_FLOW_STYLE_WORDS = ("classDef ", "style ", "class ")


@dataclass(frozen=True)
class Problem:
    """One rule a diagram breaks. `block` is 1-based within the file; 0 means outside a block."""

    block: int
    rule: str
    detail: str


def _is_relation(line: str) -> bool:
    return _RELATION.search(line) is not None


def _is_group_open(line: str) -> bool:
    stripped = line.strip()
    return stripped.endswith("{") and not _is_relation(stripped)


def _is_group_close(line: str) -> bool:
    return line.strip() == "}"


def _fences(lines: Sequence[str]) -> list[tuple[int, int]]:
    """The `(first body line, end)` index ranges of every mermaid fence, end exclusive."""
    found: list[tuple[int, int]] = []
    start: int | None = None
    for index, line in enumerate(lines):
        stripped = line.strip()
        if start is None:
            if stripped == _FENCE_OPEN:
                start = index + 1
        elif stripped == _FENCE_CLOSE:
            found.append((start, index))
            start = None
    if start is not None:
        found.append((start, len(lines)))
    return found


def _is_flow_edge(line: str) -> bool:
    stripped = line.strip()
    if stripped.startswith(("subgraph ", "linkStyle", *_FLOW_STYLE_WORDS)):
        return False
    return _FLOW_EDGE.search(_QUOTED.sub('""', stripped)) is not None


def _edge_lines(body: Sequence[str], kind: Kind = "class") -> list[str]:
    """The relation lines of a diagram body: those outside any group that carry an arrow.

    In a `flow` body an edge counts at any depth.
    """
    if kind == "flow":
        return [line for line in body if _is_flow_edge(line)]
    edges: list[str] = []
    inside = False
    for line in body:
        if inside:
            inside = not _is_group_close(line)
        elif _is_relation(line):
            edges.append(line)
        elif _is_group_open(line):
            inside = True
    return edges


def block_problems(
    text: str,
    max_chars: int = MAX_BLOCK_CHARS,
    max_edges: int = MAX_BLOCK_EDGES,
    kind: Kind = "class",
) -> list[Problem]:
    """The mermaid blocks of `text` that are too big to render.

    A block whose body (the text between its fences, lines joined by `\\n`) is `max_chars`
    (50,000) characters or more is rule `block-size`. A block with `max_edges` (500) or
    more edges is rule `block-edges`; an edge is a line outside any class or entity group
    that carries a relation arrow (`--` or `..` with its heads), so a member typed
    `Callable[..., T]` is not one. For `kind` `flow` an edge is a line with `-->`, `---`,
    `-.->` or `==>` at any depth (quoted labels do not count), and a `linkStyle` line is rule
    `flow-linkstyle`.
    """
    lines = text.split("\n")
    problems: list[Problem] = []
    for number, (start, end) in enumerate(_fences(lines), start=1):
        body = lines[start:end]
        size = len("\n".join(body))
        if size >= max_chars:
            problems.append(
                Problem(number, "block-size", f"{size} characters, limit is {max_chars - 1}")
            )
        edges = len(_edge_lines(body, kind))
        if edges >= max_edges:
            problems.append(
                Problem(number, "block-edges", f"{edges} edges, limit is {max_edges - 1}")
            )
        if kind == "flow":
            problems.extend(
                Problem(number, "flow-linkstyle", line.strip())
                for line in body
                if line.strip().startswith("linkStyle")
            )
    return problems


def duplicate_classes(text: str) -> list[Problem]:
    """A class name defined twice in one mermaid block is rule `duplicate-class`."""
    lines = text.split("\n")
    problems: list[Problem] = []
    for number, (start, end) in enumerate(_fences(lines), start=1):
        seen: set[str] = set()
        reported: set[str] = set()
        inside = False
        for line in lines[start:end]:
            if inside:
                inside = not _is_group_close(line)
                continue
            match = _CLASS_DEF.match(line.strip())
            if match is not None:
                name = match.group(1)
                if name in seen and name not in reported:
                    reported.add(name)
                    problems.append(
                        Problem(number, "duplicate-class", f"class {name} is defined twice")
                    )
                seen.add(name)
            if _is_group_open(line):
                inside = True
    return problems


def absolute_paths(text: str, roots: Sequence[str]) -> list[Problem]:
    """Each given root (a temp dir, the repo path) found in a block is rule `absolute-path`.

    The block is 1-based; an occurrence outside any mermaid block is reported as block 0.
    """
    lines = text.split("\n")
    fences = _fences(lines)
    problems: list[Problem] = []
    for root in roots:
        if not root:
            continue
        reported: set[int] = set()
        for index, line in enumerate(lines):
            if root not in line:
                continue
            block = next(
                (n for n, (start, end) in enumerate(fences, start=1) if start <= index < end), 0
            )
            if block not in reported:
                reported.add(block)
                problems.append(Problem(block, "absolute-path", f"found {root}"))
    return problems


